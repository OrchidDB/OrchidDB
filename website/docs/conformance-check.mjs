import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const base=process.env.DOCS_URL || 'http://127.0.0.1:5321';
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
const context=await browser.newContext({viewport:{width:1500,height:1000}});
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(base+'/conformance.html');
assert.equal(await page.locator('.comparison-row').count(),6533);
assert.deepEqual(await page.locator('.summary-scroll thead th').allTextContents(),['Upstream suite','Crabgraph','SQLg','PuppyGraph']);
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
for(const filter of ['crab-wins','peer-wins','adapter','failures']){
  await page.locator('#comparison-filter').selectOption(filter);
  assert.ok(await page.locator('.comparison-row:not([hidden])').count()>0,filter);
  assert.equal(await page.locator('.comparison-row:not([hidden])').evaluateAll((rows,value)=>rows.every(row=>row.dataset.flags.split(' ').includes(value)),filter),true);
}
await page.locator('#comparison-reset').click();
await page.locator('#comparison-language').selectOption('tinkerpop');
assert.equal(await page.locator('.comparison-row:not([hidden])').count(),1511);
await page.locator('#comparison-search').fill('no-such-feature-123');
await page.waitForFunction(()=>document.querySelector('#comparison-count').textContent.startsWith('0 of'));
assert.equal(await page.locator('.comparison-row:not([hidden])').count(),0);
await page.locator('#comparison-reset').click();
await page.screenshot({path:'/tmp/crabgraph-conformance-desktop.png'});
const anchor=await page.locator('.comparison-row').first().getAttribute('id');
await page.goto(base+'/conformance.html#'+anchor);
const row=page.locator('#'+anchor);
await row.locator('[data-product="upstream"] pre').waitFor();
const original=JSON.parse(await row.locator('[data-product="upstream"] pre').textContent());
assert.equal(original.id,await row.locator('[data-product="upstream"]').getAttribute('data-case'));
await row.locator('[data-product="crabgraph"] summary').click();
await row.locator('[data-product="crabgraph"] pre').waitFor();
const actual=JSON.parse(await row.locator('[data-product="crabgraph"] pre').textContent());
assert.equal(actual.id,original.id);assert.ok(actual.case_sha256);
await page.setViewportSize({width:390,height:844});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.screenshot({path:'/tmp/crabgraph-conformance-mobile.png'});
assert.deepEqual(errors,[]);
await context.close();
const nojs=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
const staticPage=await nojs.newPage();await staticPage.goto(base+'/conformance.html');
assert.equal(await staticPage.locator('.comparison-row').count(),6533);
assert.equal(await staticPage.locator('.comparison-controls').isVisible(),false);
await staticPage.locator('.upstream-group > summary').first().click();
await staticPage.locator('.comparison-row [data-product="upstream"] > summary').first().click();
const download=staticPage.locator('.comparison-row [data-product="upstream"] a').nth(1);
assert.ok(await download.isVisible());
assert.equal((await staticPage.request.get(base+await download.getAttribute('href'))).status(),200);
assert.equal(await staticPage.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await browser.close();console.log('6,533 cases: filters, exact evidence, anchors, mobile and no-JavaScript downloads passed');
