import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const base=process.env.DOCS_URL || 'http://127.0.0.1:5321';
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
const context=await browser.newContext({viewport:{width:1500,height:1000}});
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(base+'/conformance.html');
assert.equal(await page.locator('.comparison-row').count(),266);
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.locator('#comparison-filter').selectOption('crab-wins');
assert.ok(await page.locator('.comparison-row:visible').count()>0);
for(const row of await page.locator('.comparison-row:visible').all())assert.match(await row.getAttribute('data-flags'),/crab-wins/);
await page.locator('#comparison-filter').selectOption('peer-wins');
assert.ok(await page.locator('.comparison-row:visible').count()>0);
await page.locator('#comparison-filter').selectOption('enterprise');
assert.ok(await page.locator('.comparison-row:visible').count()>0);
await page.locator('#comparison-search').fill('LDAP');
assert.equal(await page.locator('.comparison-row:visible').count(),1);
await page.locator('#comparison-reset').click();
await page.locator('#comparison-language').selectOption('gremlin');
assert.equal(await page.locator('.comparison-row:visible').count(),73);
await page.locator('#comparison-search').fill('no-such-feature-123');
assert.equal(await page.locator('.comparison-row:visible').count(),0);
await page.locator('#comparison-reset').click();
await page.screenshot({path:'/tmp/crabgraph-conformance-desktop.png'});
await page.goto(base+'/conformance.html#cypher.node_scan');
assert.equal(await page.locator('[id="cypher.node_scan"] details').first().getAttribute('open'),'');
await page.setViewportSize({width:390,height:844});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.screenshot({path:'/tmp/crabgraph-conformance-mobile.png'});
assert.deepEqual(errors,[]);
await context.close();
const nojs=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
const staticPage=await nojs.newPage();await staticPage.goto(base+'/conformance.html');
assert.equal(await staticPage.locator('.comparison-row').count(),266);
assert.equal(await staticPage.locator('.comparison-controls').isVisible(),false);
await staticPage.locator('[id="cypher.node_scan"] summary').first().click();
assert.ok(await staticPage.locator('[id="cypher.node_scan"] pre').first().isVisible());
assert.equal(await staticPage.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await browser.close();console.log('Conformance filters, evidence, anchors, mobile overflow and no-JavaScript rendering passed');
